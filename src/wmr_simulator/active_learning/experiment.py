"""Experiment workspace for the iterative active-learning loop.

An experiment lives in its own directory and holds one folder per iteration:

    experiments/<name>/
      experiment.yaml               flags + stage hyperparameters (editable)
      iteration_01/
        robot_config.yaml           current-best robot params + gains (iteration input)
        ROBOTCFG.CFG                firmware export of robot_config.yaml (copy to SD card)
        GAINMLP.JSN                 firmware export of the error-MLP gain schedule,
                                    when enabled (copy to SD card next to ROBOTCFG.CFG)
        robot_config_static_gains.yaml  same params with the static-tune gains
        ROBOTCFG_static.CFG         firmware export of it, for benchmarking the
                                    static gains against the gain MLP on the robot
                                    (rename to ROBOTCFG.CFG on the SD card, and
                                    remove GAINMLP.JSN)
        problem.yaml                generated: base problem + current params/gains
        problem_identified.yaml     generated by the identify stage (updated robot block)
        identification_trajectory/  informative ID trajectory (.pkl + .JSN for the robot)
        tuning_trajectories/        gain-tuning reference trajectory set (.pkl)
        data/                       drop SD-card logs here; decode-logs writes .csv
                                    (every log directly in here is identification
                                    data; subdirectories hold baseline comparison
                                    runs and are skipped by the identify stage.
                                    With mujoco_deployment.enabled the logs are
                                    written here by the simulate-deployment
                                    stage instead of carried over from the robot)
        data/benchmark/             repeat runs of the fixed baseline reference,
                                    recorded by the benchmark stage under this
                                    iteration's deployed controller; the progress
                                    plot scores every iteration on them
        data/benchmark_static/      the same runs under this iteration's
                                    static-gain controller, so the two
                                    controller options can be compared --
                                    ROBOTCFG_static.CFG from iteration 2 on, and
                                    in iteration 1 the stock ROBOTCFG.CFG, whose
                                    parametrization is still the identity and
                                    which is therefore the only set it records
        benchmark/                  the baseline reference as it was driven
                                    (bridged when it does not close on itself)
        results/                    identification.yaml, gains.yaml, residual_model.pkl
        visualize/                  plots of this iteration, plus the
                                    cross-iteration figures regenerated as it
                                    runs (identified_parameters.pdf,
                                    pipeline_progress.pdf, baseline_runs_*.pdf)
      iteration_02/                 created by the finalize stage from iteration_01 results

All stage results are plain files, so the loop can be interrupted at any point
(e.g. to collect robot data from the SD card) and resumed stage by stage.
"""

