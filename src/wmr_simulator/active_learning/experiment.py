"""Experiment workspace for the iterative active-learning loop.

An experiment lives in its own directory and holds one folder per iteration:

    experiments/<name>/
      experiment.yaml               flags + stage hyperparameters (editable)
      iteration_01/
        robot_config.yaml           current-best robot params + gains (iteration input)
        ROBOTCFG.CFG                firmware export of robot_config.yaml (copy to SD card)
        GAINMLP.JSN                 firmware export of the error-MLP gain schedule,
                                    when enabled (copy to SD card next to ROBOTCFG.CFG)
        problem.yaml                generated: base problem + current params/gains
        problem_identified.yaml     generated by the identify stage (updated robot block)
        identification_trajectory/  informative ID trajectory (.pkl + .JSN for the robot)
        tuning_trajectories/        gain-tuning reference trajectory set (.pkl)
        data/                       drop SD-card logs here; decode-logs writes .csv
        results/                    identification.yaml, gains.yaml, residual_model.pkl
        visualize/                  plots of this iteration
      iteration_02/                 created by the finalize stage from iteration_01 results

All stage results are plain files, so the loop can be interrupted at any point
(e.g. to collect robot data from the SD card) and resumed stage by stage.
"""

